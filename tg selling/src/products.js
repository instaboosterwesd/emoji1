const parseDurations = text => {
  if (text === 'Out of Stock') return [];
  return [...text.matchAll(/(.+?)\s*\[Stock:\s*(\d+)\]/g)].map(match => ({
    label: match[1].trim(),
    stock: Number(match[2]),
  }));
};

